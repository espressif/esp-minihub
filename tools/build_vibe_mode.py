"""Build the Vibe Mode factory image (components/minihub_vibe/subproject).

This is the nested IDF project that produces vibe_mode.bin for the app,factory
partition — the same role as the bootloader subproject, not a Host product under
application/. Host products pull it in through
components/minihub_vibe/project_include.cmake (``idf.py build`` builds the
``vibe_mode`` target). This script is that target's command, and also the
``./tools/build_firmware.py vibe`` entry point for a standalone rebuild.

Usage:
  ./tools/build_firmware.py vibe
  ./tools/build_firmware.py -app minihub_lcd vibe
  python3 tools/build_vibe_mode.py --build-dir application/minihub/build/vibe_mode \\
      --partitions application/minihub/partitions.csv
"""
from __future__ import annotations

import argparse
import os
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
DEFAULT_SRC = ROOT / "components" / "minihub_vibe" / "subproject"
DEFAULT_APP = "minihub"
VIBE_BIN = "vibe_mode.bin"


def idf_path() -> Path:
    return Path(os.environ.get("IDF_PATH", str(ROOT / "esp-idf")))


def write_partitions_fragment(partitions: Path) -> Path:
    """Point the subproject at the Host product's partitions.csv.

    Written under subproject/.host_fragments/ — never into the out-of-tree
    build dir — so a fresh ``set-target`` does not see a non-CMake build/
    that ``fullclean`` refuses to delete.
    """
    frag_dir = DEFAULT_SRC / ".host_fragments"
    frag_dir.mkdir(parents=True, exist_ok=True)
    # One fragment per product (minihub vs minihub_lcd) when paths differ.
    product = partitions.resolve().parent.name
    frag = frag_dir / f"{product}.sdkconfig.partitions.defaults"
    abs_csv = partitions.resolve()
    frag.write_text(
        "# Generated by tools/build_vibe_mode.py — do not edit.\n"
        "CONFIG_PARTITION_TABLE_CUSTOM=y\n"
        f'CONFIG_PARTITION_TABLE_CUSTOM_FILENAME="{abs_csv}"\n'
        f'CONFIG_PARTITION_TABLE_FILENAME="{abs_csv}"\n',
        encoding="utf-8",
    )
    return frag


def scrub_non_cmake_build_dir(build_dir: Path) -> None:
    if build_dir.is_dir() and not (build_dir / "CMakeCache.txt").is_file():
        print(f"Removing non-CMake {build_dir} before idf.py set-target", flush=True)
        shutil.rmtree(build_dir)


def run_idf(src_dir: Path, build_dir: Path, args: list[str],
            sdkconfig_defaults: str) -> int:
    idf = idf_path()
    export_sh = idf / "export.sh"
    prefix = f'source "{export_sh}" >/dev/null 2>&1 && ' if export_sh.is_file() else ""
    # -C / -B keep the nested build under the Host build tree, not in subproject/.
    cmd = ["idf.py", "--preview", "-C", str(src_dir), "-B", str(build_dir), *args]
    script = (
        prefix
        + f'export IDF_PATH={shlex.quote(str(idf))} && '
        + f'export SDKCONFIG_DEFAULTS={shlex.quote(sdkconfig_defaults)} && '
        + subprocess.list2cmdline(cmd)
    )
    print(f"=== {' '.join(cmd)} ===", flush=True)
    print(f"    SDKCONFIG_DEFAULTS={sdkconfig_defaults}", flush=True)
    return subprocess.run(["bash", "-c", script], cwd=str(ROOT)).returncode


def build(src_dir: Path, build_dir: Path, partitions: Path) -> int:
    frag = write_partitions_fragment(partitions)
    defaults = f"{src_dir / 'sdkconfig.defaults'};{frag}"
    sdkconfig = build_dir / "sdkconfig"
    # Fresh tree: set-target. Existing tree: plain build (set-target fullclean
    # refuses non-CMake dirs and wipes a usable tree).
    if not sdkconfig.is_file():
        if (build_dir / "CMakeCache.txt").is_file():
            rc = run_idf(src_dir, build_dir, ["reconfigure"], defaults)
        else:
            scrub_non_cmake_build_dir(build_dir)
            rc = run_idf(src_dir, build_dir, ["set-target", "esp32s31"], defaults)
        if rc != 0:
            return rc
    rc = run_idf(src_dir, build_dir, ["build"], defaults)
    if rc != 0:
        return rc
    out = build_dir / VIBE_BIN
    if not out.is_file():
        print(f"ERROR: {out} missing after build", file=sys.stderr)
        return 1
    print(f"vibe_mode image: {out}", flush=True)
    return check_fits_factory(build_dir)


def check_fits_factory(build_dir: Path) -> int:
    """Fail if vibe_mode.bin does not fit the app,factory (vibe_mode) slot."""
    table = build_dir / "partition_table" / "partition-table.bin"
    binary = build_dir / VIBE_BIN
    if not table.is_file():
        print(f"WARNING: {table} missing — skip factory size check", file=sys.stderr)
        return 0
    tool = idf_path() / "components" / "partition_table" / "check_sizes.py"
    cmd = [
        sys.executable, str(tool),
        "--offset", "0x8000",
        "partition", "--type", "app", "--subtype", "factory",
        str(table), str(binary),
    ]
    print(f"=== check_sizes factory <- {binary.name} ===", flush=True)
    return subprocess.run(cmd, cwd=str(ROOT)).returncode


def parse_argv(argv: list[str]) -> argparse.Namespace:
    app = (os.environ.get("MINIHUB_APP") or DEFAULT_APP).strip() or DEFAULT_APP
    rest: list[str] = []
    i = 0
    while i < len(argv):
        a = argv[i]
        if a in ("-app", "--app") and i + 1 < len(argv):
            app = argv[i + 1]
            i += 2
            continue
        if a.startswith("--app="):
            app = a.split("=", 1)[1]
            i += 1
            continue
        rest.append(a)
        i += 1

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src-dir", type=Path, default=DEFAULT_SRC,
                    help="Vibe Mode IDF project (default: components/minihub_vibe/subproject)")
    ap.add_argument("--build-dir", type=Path, default=None,
                    help="out-of-tree build dir (default: application/<app>/build/vibe_mode)")
    ap.add_argument("--partitions", type=Path, default=None,
                    help="Host partitions.csv (default: application/<app>/partitions.csv)")
    ap.add_argument("--flash", action="store_true",
                    help="write the factory partition over UART after build")
    ns = ap.parse_args(rest)
    ns.app = app
    if ns.partitions is None:
        ns.partitions = ROOT / "application" / app / "partitions.csv"
    if ns.build_dir is None:
        ns.build_dir = ROOT / "application" / app / "build" / "vibe_mode"
    return ns


def factory_offset(partitions: Path) -> str:
    for line in partitions.read_text(encoding="utf-8").splitlines():
        parts = [p.strip() for p in line.split(",")]
        if len(parts) >= 4 and parts[0] == "vibe_mode" and parts[2] == "factory":
            return hex(int(parts[3], 0))
    raise SystemExit(f"ERROR: no vibe_mode factory row in {partitions}")


def flash_bin(partitions: Path, bin_path: Path) -> int:
    idf = idf_path()
    export_sh = idf / "export.sh"
    prefix = f'source "{export_sh}" >/dev/null 2>&1 && ' if export_sh.is_file() else ""
    off = factory_offset(partitions)
    script = prefix + f'esptool.py --chip esp32s31 write_flash {off} "{bin_path}"'
    return subprocess.run(["bash", "-c", script], cwd=str(ROOT)).returncode


def main(argv: list[str] | None = None) -> int:
    args = parse_argv(list(argv) if argv is not None else sys.argv[1:])
    os.environ["MINIHUB_APP"] = args.app
    src = args.src_dir.resolve()
    if not (src / "CMakeLists.txt").is_file():
        print(f"ERROR: vibe subproject missing: {src}", file=sys.stderr)
        return 1
    if not args.partitions.is_file():
        print(f"ERROR: partitions.csv missing: {args.partitions}", file=sys.stderr)
        return 1

    print(f"vibe src={src}", flush=True)
    print(f"vibe build={args.build_dir.resolve()}", flush=True)
    print(f"vibe partitions={args.partitions.resolve()}", flush=True)

    rc = build(src, args.build_dir.resolve(), args.partitions.resolve())
    if rc != 0:
        return rc
    if args.flash:
        return flash_bin(args.partitions.resolve(), args.build_dir.resolve() / VIBE_BIN)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
