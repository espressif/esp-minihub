"""components/minihub_lcd/ui_contract.json -> ui_contract.gen.h (one place per name)."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "components" / "minihub_lcd" / "ui_contract.json"

HEADER = """/* Auto-generated by tools/gen_lcd_ui_contract.py — do not edit.
 * SPDX-FileCopyrightText: 2026 MiniHub Contributors
 * SPDX-License-Identifier: Apache-2.0
 */
#pragma once
"""


def emit(lines: list[str], name: str, value: str) -> None:
    lines.append(f'#define {name} "{value}"')


def render(contract: dict) -> str:
    if contract.get("schema") != "minihub.lcd.ui_contract/1":
        raise SystemExit(f"unsupported ui_contract schema: {contract.get('schema')!r}")

    lines = [HEADER, f'#define LCD_CONTRACT_ROOT_VERSION "{contract["root_version"]}"',
             f'#define LCD_CONTRACT_FLOW_ID "{contract["flow_id"]}"', ""]

    for key, val in sorted(contract["counts"].items()):
        lines.append(f"#define LCD_COUNT_{key.upper()} {val}")
    lines.append("")

    for key, values in sorted(contract["enums"].items()):
        joined = ", ".join(f'"{v}"' for v in values)
        lines.append(f"#define LCD_ENUM_{key.upper()} {joined}")
        lines.append(f"#define LCD_ENUM_{key.upper()}_N {len(values)}")
    lines.append("")

    for key, val in sorted(contract["views"].items()):
        emit(lines, f"LCD_VIEW_{key}", val)
    lines.append("")
    for key, spec in sorted(contract["view_patterns"].items()):
        emit(lines, f"LCD_VIEW_PATTERN_{key}", spec["format"])
    lines.append("")
    for key, val in sorted(contract["actions"].items()):
        emit(lines, f"LCD_ACTION_{key}", val)
    lines.append("")
    for key, spec in sorted(contract["action_patterns"].items()):
        emit(lines, f"LCD_ACTION_PATTERN_{key}", spec["format"])
    lines.append("")
    for key, spec in sorted((contract.get("templates") or {}).items()):
        emit(lines, f"LCD_TEMPLATE_{key}_ID", spec["template_id"])
        emit(lines, f"LCD_TEMPLATE_{key}_PARENT", spec["parent"])
        lines.append(
            "#define LCD_TEMPLATE_%s_CHILDREN %s"
            % (key, ", ".join(f'"{c}"' for c in spec["children"]))
        )
        if "instance_format" in spec:
            emit(lines, f"LCD_TEMPLATE_{key}_INSTANCE", spec["instance_format"])
        if "instance_prefix" in spec:
            emit(lines, f"LCD_TEMPLATE_{key}_INSTANCE_PREFIX", spec["instance_prefix"])
        if "count_key" in spec:
            lines.append(
                f'#define LCD_TEMPLATE_{key}_COUNT {contract["counts"][spec["count_key"]]}'
            )
        if "action" in spec:
            emit(lines, f"LCD_TEMPLATE_{key}_ACTION", spec["action"])
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--check", action="store_true", help="fail if the file is stale")
    a = ap.parse_args()
    want = render(json.loads(CONTRACT.read_text(encoding="utf-8")))
    if a.check:
        have = a.out.read_text(encoding="utf-8") if a.out.is_file() else ""
        if have != want:
            print(f"stale: {a.out}", file=sys.stderr)
            return 1
        return 0
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(want, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
