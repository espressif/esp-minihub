"""LCD UI i18n: ui/i18n/strings.json -> per-language constants + C++ header.

The dictionary is the single source of truth. Brookesia substitutes
``${constant.strings.<key>}`` at parse time, so the language is chosen by
``root.json`` variants. The generated C++ header carries the same strings for
labels that firmware fills at runtime (``lcd_tr()``), so the two never drift.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LCD = ROOT / "components" / "minihub_lcd"
SOURCE = LCD / "ui" / "i18n" / "strings.json"
CONSTANTS = LCD / "ui" / "constants"

SCHEMA = "minihub.lcd.i18n/1"
LANGUAGES = ("zh", "en")
KEY_RE = re.compile(r"^[a-z][a-z0-9_]*$")

HEADER_TOP = """/* Auto-generated by tools/gen_lcd_i18n.py - do not edit.
 * SPDX-FileCopyrightText: 2026 MiniHub Contributors
 * SPDX-License-Identifier: Apache-2.0
 */
#pragma once

#include <array>

/* Same dictionary as ui/i18n/strings.json. Firmware-side labels call
 * lcd_tr(LCD_STR_*) so a language switch needs no runtime JSON parsing.
 * Members are string literals: lcd_tr() can return them as C strings. */
namespace lcd_i18n {
struct Entry {
    const char *key;
    const char *zh;
    const char *en;
};

inline constexpr std::array<Entry, %d> kEntries{{
"""


def load_source() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if data.get("schema") != SCHEMA:
        raise SystemExit(f"unsupported LCD i18n schema: {data.get('schema')!r}")
    if list(data.get("languages") or []) != list(LANGUAGES):
        raise SystemExit(f"languages must be {list(LANGUAGES)}")
    strings = data.get("strings")
    if not isinstance(strings, dict) or not strings:
        raise SystemExit("strings must be a non-empty object")
    for key, entry in strings.items():
        if not KEY_RE.match(key):
            raise SystemExit(f"invalid i18n key: {key!r} (use lower_snake_case)")
        if not isinstance(entry, dict) or set(entry) != set(LANGUAGES):
            raise SystemExit(f"key {key!r} must define exactly {list(LANGUAGES)}")
        for lang in LANGUAGES:
            value = entry[lang]
            if not isinstance(value, str) or not value:
                raise SystemExit(f"key {key!r}/{lang} must be a non-empty string")
    return data


def c_string(value: str) -> str:
    """JSON string syntax is a subset of C++ here; emit UTF-8 verbatim."""
    if any(ch in value for ch in ("\\", '"')):
        raise SystemExit(f"escape sequences are not supported in i18n values: {value!r}")
    return json.dumps(value, ensure_ascii=False)


def macro_name(key: str) -> str:
    return "LCD_STR_" + key.upper()


def render_header(strings: dict) -> str:
    lines = [HEADER_TOP % len(strings)]
    for key in sorted(strings):
        entry = strings[key]
        lines.append("    {%s, %s, %s}," % (c_string(key), c_string(entry["zh"]),
                                            c_string(entry["en"])))
    lines.append("}};")
    lines.append("}  // namespace lcd_i18n")
    lines.append("")
    for key in sorted(strings):
        lines.append(f'#define {macro_name(key)} {c_string(key)}')
    lines.append("")
    lines.append('#define LCD_LANG_ZH "zh"')
    lines.append('#define LCD_LANG_EN "en"')
    lines.append("")
    return "\n".join(lines) + "\n"


def render_constant(strings: dict, lang: str) -> str:
    asset = {
        "type": "constant",
        "data": {"strings": {key: entry[lang] for key, entry in strings.items()}},
    }
    return json.dumps(asset, ensure_ascii=False, indent=2) + "\n"


def write_if_changed(path: Path, text: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--header", type=Path, help="write the C++ header here")
    ap.add_argument("--check", action="store_true",
                    help="fail when the checked-in language assets are stale")
    args = ap.parse_args()

    data = load_source()
    strings = data["strings"]

    changed = []
    for lang in LANGUAGES:
        target = CONSTANTS / f"i18n_{lang}.json"
        text = render_constant(strings, lang)
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                print(f"stale: {target}", file=sys.stderr)
                return 1
        elif write_if_changed(target, text):
            changed.append(str(target.relative_to(ROOT)))

    if args.header:
        want = render_header(strings)
        if args.check:
            have = args.header.read_text(encoding="utf-8") if args.header.is_file() else ""
            if have != want:
                print(f"stale: {args.header}", file=sys.stderr)
                return 1
        elif write_if_changed(args.header, want):
            changed.append(str(args.header))

    if changed and not args.check:
        print("generated: " + ", ".join(changed))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
