"""Sync config/minihub_manifest.yml → idf_component.yml, CMake, adapters_setup."""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:
    print("PyYAML required: pip install pyyaml", file=sys.stderr)
    sys.exit(1)


def deep_merge(base: dict[str, Any], overlay: dict[str, Any]) -> dict[str, Any]:
    out = dict(base)
    for key, val in overlay.items():
        if key == "extends":
            continue
        if isinstance(val, dict) and isinstance(out.get(key), dict):
            out[key] = deep_merge(out[key], val)
        elif isinstance(val, list) and isinstance(out.get(key), list):
            if key == "require":
                seen = set(out[key])
                out[key] = out[key] + [x for x in val if x not in seen]
            elif key == "adapters":
                # Child profile fully replaces adapter registration list
                out[key] = list(val)
            elif key == "sdkconfig_features":
                # Child fully replaces feature list (avoid concat duplicates)
                out[key] = list(val)
            else:
                out[key] = out[key] + val
        else:
            out[key] = val
    return out


def resolve_profile(manifest: dict[str, Any], name: str) -> dict[str, Any]:
    profiles = manifest.get("profiles") or {}
    if name not in profiles:
        raise SystemExit(f"Unknown profile: {name}")
    prof = profiles[name]
    if "extends" in prof:
        base = resolve_profile(manifest, prof["extends"])
        return deep_merge(base, prof)
    return prof


def yaml_dump(data: dict[str, Any]) -> str:
    return yaml.dump(data, default_flow_style=False, allow_unicode=True, sort_keys=False)


def gen_adapters_setup(adapters: list[Any]) -> str:
    lines = [
        "/* Auto-generated by tools/sync_host_manifest.py — do not edit */",
        "/* SPDX-FileCopyrightText: 2026 MiniHub Contributors */",
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "",
        '#include "minihub_adapter.h"',
        '#include "esp_log.h"',
        '#include "sdkconfig.h"',
        "",
    ]
    externs = []
    register_calls = []
    for item in adapters:
        if isinstance(item, str):
            name = item
            kconfig = None
            dynamic = False
            host_static = False
        else:
            name = item["name"]
            kconfig = item.get("kconfig")
            dynamic = bool(item.get("dynamic"))
            host_static = bool(item.get("host_static"))
        # Store-only plugins: no host .c symbol; loaded via module loader.
        if dynamic and not host_static:
            continue
        externs.append(f"extern const minihub_adapter_t {name}_adapter;")
        guard_open = []
        guard_close = []
        if kconfig:
            guard_open.append(f"#if CONFIG_{kconfig}")
            guard_close.append("#endif")
        for g in guard_open:
            register_calls.append(g)
        register_calls.append(f"    err = minihub_adapter_register(&{name}_adapter);")
        register_calls.append(f"    if (err != ESP_OK) {{")
        register_calls.append(f'        ESP_LOGE(TAG, "register {name} adapter failed: %s", esp_err_to_name(err));')
        register_calls.append(f"        return err;")
        register_calls.append(f"    }}")
        for g in guard_close:
            register_calls.append(g)

    lines.extend(externs)
    lines.extend([
        "",
        'static const char *TAG = "adapters_setup";',
        "",
        "esp_err_t minihub_adapters_register_all(void)",
        "{",
        "    esp_err_t err;",
    ])
    lines.extend(register_calls)
    lines.extend([
        "    return ESP_OK;",
        "}",
        "",
    ])
    return "\n".join(lines)


def normalize_require_item(item: Any) -> tuple[str, str | None]:
    if isinstance(item, str):
        return item, None
    return item["name"], item.get("kconfig")


def gen_cmake_requires(require: list[Any], adapters: list[Any]) -> str:
    # Dynamic plugins (Store .mhub) are never Host CMake components — even as a
    # CONFIG_MINIHUB_DYNAMIC_MODULES=n fallback (those sources live under deploy only).
    dynamic_plugin_names = {
        (item["name"] if isinstance(item, dict) else item)
        for item in adapters
        if isinstance(item, dict)
        and item.get("dynamic")
        and not item.get("host_static")
    }
    names: list[str] = []
    for item in require:
        name, _ = normalize_require_item(item)
        comp = name
        if comp.startswith("adapter_"):
            short = comp[8:]
        else:
            short = comp
        if short in dynamic_plugin_names:
            continue
        names.append(comp)
    joined = "\n             ".join(names)
    return f"""# Auto-generated by tools/sync_host_manifest.py — do not edit
set(MINIHUB_MAIN_REQUIRES
             {joined}
)
"""


def sync(project_root: Path, app_name: str) -> None:
    manifest_path = project_root / "config" / "minihub_manifest.yml"
    with manifest_path.open(encoding="utf-8") as f:
        manifest = yaml.safe_load(f)

    app_name = (app_name or "minihub").strip() or "minihub"
    os.environ["MINIHUB_APP"] = app_name

    sys.path.insert(0, str(project_root / "tools"))
    from compose_sdkconfig import (  # noqa: E402
        append_local_overrides,
        app_feature_list,
        app_has_feature,
        expand_features,
    )

    # Component set: product name, or LCD overlay when app.yml includes lcd feature
    if app_name == "minihub" and app_has_feature(project_root, app_name, "lcd"):
        profile_name = "_minihub_lcd"
    elif app_name in (manifest.get("profiles") or {}):
        profile_name = app_name
    else:
        profile_name = manifest.get("profile") or "minihub"

    prof = resolve_profile(manifest, profile_name)
    gen_dir = project_root / "cmake" / "generated"
    gen_dir.mkdir(parents=True, exist_ok=True)

    components = prof.get("components") or {}
    require = components.get("require") or []
    adapters = components.get("adapters") or []
    idf_deps = prof.get("idf_dependencies") or {}

    app_main = project_root / "application" / app_name / "main"
    if not app_main.is_dir():
        app_main = project_root / "main"
    if not app_main.is_dir():
        raise FileNotFoundError(f"application main/ missing for MINIHUB_APP={app_name}")

    main_yml = app_main / "idf_component.yml"
    if app_name != "claw_minihub":
        main_yml.write_text(yaml_dump({"dependencies": idf_deps}), encoding="utf-8")
        print(f"  → {main_yml}")
    else:
        print(f"  → {main_yml} (skipped; claw_minihub manifest is hand-maintained)")

    lcd_yml = project_root / "components" / "minihub_lcd" / "idf_component.yml"
    comp_manifests = prof.get("component_manifests") or {}
    if comp_manifests.get("minihub_lcd"):
        lcd_yml.write_text(
            yaml_dump(comp_manifests["minihub_lcd"]),
            encoding="utf-8",
        )
    elif lcd_yml.exists():
        lcd_yml.unlink()

    adapters_c = app_main / "adapters_setup.generated.c"
    adapters_c.write_text(gen_adapters_setup(adapters), encoding="utf-8")

    cmake_path = gen_dir / "minihub_components.cmake"
    cmake_path.write_text(gen_cmake_requires(require, adapters), encoding="utf-8")

    (gen_dir / "profile.txt").write_text(app_name + "\n", encoding="utf-8")
    partition = prof.get("partition_table", "partitions.csv")
    (gen_dir / "partition_table.txt").write_text(partition + "\n", encoding="utf-8")

    # Prefer product app.yml features over manifest sdkconfig_features
    try:
        sdk_features, _board = app_feature_list(project_root, app_name)
    except FileNotFoundError:
        sdk_features = list(prof.get("sdkconfig_features") or [])
    if sdk_features:
        sdk_extra = append_local_overrides(
            project_root, app_name, expand_features(project_root, app_name, list(sdk_features))
        )
    else:
        sdk_extra = list(prof.get("sdkconfig_extra") or [])
    (gen_dir / "sdkconfig_extra.txt").write_text(
        "\n".join(sdk_extra) + ("\n" if sdk_extra else ""), encoding="utf-8"
    )

    lcd_ui = bool(components.get("lcd_ui"))
    (gen_dir / "lcd_ui.txt").write_text("1\n" if lcd_ui else "0\n", encoding="utf-8")

    print(f"sync_host_manifest: app={app_name} components={profile_name} partition={partition} lcd_ui={lcd_ui}")
    print(f"  → {adapters_c}")
    print(f"  → {cmake_path}")
    if lcd_yml.exists():
        print(f"  → {lcd_yml}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--app",
        default=os.environ.get("MINIHUB_APP", ""),
        help="Product / application folder (default: MINIHUB_APP or minihub)",
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
    )
    args = parser.parse_args()

    app = args.app or os.environ.get("MINIHUB_APP", "")
    if not app:
        app_file = args.project_root / ".minihub_app"
        if app_file.exists():
            app = app_file.read_text(encoding="utf-8").strip()
    app = app or "minihub"
    sync(args.project_root, app)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
