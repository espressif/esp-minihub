"""Deploy-root server for plugins, firmware, assets, and web (default :8080).

  MINIHUB_PLUGINS_DEPLOY_DIR  (default ~/workspace/minihub_store)

Routes:
  GET /api/catalog            aggregate Stores/<chip-or-Common>/<id>/catalog.json;
                                with ?mac&chip&abi_version&abi_total_hash the server
                                performs ABI authenticity + per-symbol compatibility
                                checks and returns only the latest compatible build
                                per plugin id. Zero compatible -> {status:
                                "no_plugin_for_version"} + optional firmware_upgrade.
  GET /api/firmware           walk Firmwares/<chip>/<version>/ and build the array
  GET /api/web               walk Webs/<version>/ and build the web manifest
  GET /api/assets            walk Assets/ and build the asset manifest
  GET /api/assets/device/<id> device icon + per-parameter meta (404 if unknown);
                             a type absent from model/devices.csv is served from
                             Assets/images/devices/<id>.svg when that file exists
  GET /api/assets/parameter/<param> generic parameter registry entry (404 if unknown)
  GET /files/<path>           file under the deploy root (rejects '..' and escapes)

``mac`` is used only for the server-side overrides authorization. Missing
query params fall back to the legacy behavior (return the full aggregated
catalog). host_abi_versions.json (under Stores/) and overrides.json at the deploy root drive the
ABI checks; when absent the server degrades to passthrough (no enforcement).

Plugin packages live at Stores/ESP32S31/<id>/<id>.mhub for a concrete chip and
Stores/Common/<id>/<id>.mhub when targets is ["ALL"]. Firmware folders hold
<name>.bin and release_notes.txt only -- no json. Asset and web indexes are
generated by gen_deploy_index.py.
"""

