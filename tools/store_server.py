def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def load_host_abi(deploy: Path) -> list | None:
    """The contract is an array of per-version entries under Stores/."""
    return _read_json(deploy / "Stores" / "host_abi_versions.json")


def host_abi_symbols_for(host_abi: list | None, abi_version: int) -> dict | None:
    """Flat ``{name: hash}`` for a published abi_version, or None if unknown."""
    if not isinstance(host_abi, list):
        return None
    for entry in host_abi:
        if entry.get("version") == abi_version:
            return entry.get("symbols") or {}
    return None


def load_overrides(deploy: Path) -> dict:
    obj = _read_json(deploy / "overrides.json")
    return obj if isinstance(obj, dict) else {}


def _iter_plugin_catalog_files(deploy: Path):
    """Yield every ``catalog.json`` under ``Stores/``.

    Compatible with both the existing flat layout
    ``Stores/<bucket>/<id>/catalog.json`` and the planned versioned layout
    ``Stores/<bucket>/<id>/<version>/catalog.json``.
    """
    seen: set[Path] = set()
    for pat in ("Stores/*/*/catalog.json", "Stores/*/*/*/catalog.json"):
        for p in sorted(deploy.glob(pat)):
            if p not in seen:
                seen.add(p)
                yield p


def load_plugin_catalog(deploy: Path) -> list:
    """Aggregate ``Stores/<bucket>/<id>/catalog.json`` (legacy, unvalidated)."""
    best: dict[str, dict] = {}
    for path in _iter_plugin_catalog_files(deploy):
        obj = _read_json(path)
        if obj is None:
            continue
        rows = obj if isinstance(obj, list) else [obj]
        for item in rows:
            if not isinstance(item, dict) or not isinstance(item.get("id"), str):
                continue
            mid = item["id"]
            prev = best.get(mid)
            if prev is None or catalog_preference(item) < catalog_preference(prev):
                best[mid] = item
    return [best[key] for key in sorted(best)]


def load_all_plugin_entries(deploy: Path) -> list:
    """Every catalog entry across all buckets/versions (for latest + overrides)."""
    out: list = []
    for path in _iter_plugin_catalog_files(deploy):
        obj = _read_json(path)
        if obj is None:
            continue
        rows = obj if isinstance(obj, list) else [obj]
        for item in rows:
            if isinstance(item, dict) and isinstance(item.get("id"), str):
                out.append(item)
    return out


def _version_tuple(version: str):
    parts = []
    for p in (version or "").split("."):
        try:
            parts.append(int(re.sub(r"[^0-9].*$", "", p) or 0))
        except ValueError:
            parts.append(0)
    return tuple(parts)


def latest_per_id(entries: list) -> dict[str, dict]:
    """Latest build per plugin id (bucket preference, then highest semver)."""
    best: dict[str, dict] = {}
    for item in entries:
        mid = item.get("id")
        if not isinstance(mid, str):
            continue
        prev = best.get(mid)
        if prev is None:
            best[mid] = item
            continue
        if catalog_preference(item) < catalog_preference(prev):
            best[mid] = item
            continue
        if _version_tuple(item.get("version", "")) > _version_tuple(prev.get("version", "")):
            best[mid] = item
    return best


def catalog_compatible(entry: dict, host_abi: list | None, abi_version: int) -> bool:
    """True when every symbol the plugin uses matches the host's abi_version entry."""
    abi = entry.get("abi")
    if not isinstance(abi, dict):
        return True  # legacy plugin without an abi block: passthrough
    if abi.get("abi_version") != abi_version:
        return False
    symbols = abi.get("symbols") or {}
    if not symbols:
        return True
    host_symbols = host_abi_symbols_for(host_abi, abi_version)
    if not host_symbols:
        return False
    for name, h in symbols.items():
        if host_symbols.get(name) != h:
            return False
    return True


def plugin_matches_chip(entry: dict, chip: str) -> bool:
    """True when the entry may be installed on ``chip``.

    ``targets`` holds chip folder names; ``ALL`` / ``*`` mean every chip. The
    device advertises ?chip=, and an entry aimed at another chip must not be
    offered -- a stale or hand-edited per-plugin catalog.json included.
    """
    targets = entry.get("targets")
    if not isinstance(targets, list) or not targets:
        return True  # legacy entry without targets: passthrough
    if not chip:
        return True  # request without a chip: do not filter
    want = chip.strip().lower()
    for t in targets:
        if not isinstance(t, str):
            continue
        v = t.strip().lower()
        if v in ("all", "*") or v == want:
            return True
    return False


def find_plugin_version(entries: list, plugin_id: str, version: str) -> dict | None:
    for item in entries:
        if item.get("id") == plugin_id and item.get("version") == version:
            return item
    return None


def build_firmware_upgrade(deploy: Path, chip: str, abi_version: int) -> dict:
    """Advise the device to upgrade firmware when no compatible plugin exists."""
    root = deploy / "Firmwares"
    available = False
    firmware_url = ""
    if chip and (root / chip).is_dir():
        for ver_dir in sorted(p for p in (root / chip).iterdir() if p.is_dir() and not p.name.startswith(".")):
            bins = sorted(p for p in ver_dir.glob("*.bin") if p.is_file())
            if bins:
                available = True
                firmware_url = f"/files/Firmwares/{chip}/{ver_dir.name}/{bins[0].name}"
                break
    return {
        "available": available,
        "min_abi_version": abi_version,
        "firmware_url": firmware_url,
    }


def load_firmware_catalog(deploy: Path) -> list:
    """Build the firmware array from Firmwares/<chip>/<version>/."""
    root = deploy / "Firmwares"
    if not root.is_dir():
        return []
    items: list = []
    for chip_dir in sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith(".")):
        chip = chip_dir.name
        for ver_dir in sorted(p for p in chip_dir.iterdir() if p.is_dir() and not p.name.startswith(".")):
            version = ver_dir.name
            # Firmware notes use the same plural file name as Web bundles:
            # release_notes.txt. A leftover singular release_note.txt is still
            # read (releases published before the rename) but is flagged.
            note_path = ver_dir / "release_notes.txt"
            legacy_path = ver_dir / "release_note.txt"
            if not note_path.is_file() and legacy_path.is_file():
                print(
                    f"[store] WARN {ver_dir}: legacy release_note.txt in use; "
                    "rename it to release_notes.txt",
                    file=sys.stderr,
                )
                note_path = legacy_path
            note = note_path.read_text(encoding="utf-8", errors="replace") if note_path.is_file() else ""
            bins = sorted(p for p in ver_dir.glob("*.bin") if p.is_file())
            for blob in bins:
                stem = blob.stem
                item_id = f"{chip}-{version}" if len(bins) == 1 else f"{chip}-{version}-{stem}"
                items.append(
                    {
                        "id": item_id,
                        "name": stem,
                        "version": version,
                        "chip": chip,
                        "targets": [chip],
                        "sha256": sha256_file(blob),
                        "size": blob.stat().st_size,
                        "release_note": note,
                        "url": f"/files/Firmwares/{chip}/{version}/{blob.name}",
                    }
                )
    return items


def resolve_deploy_file(deploy: Path, raw_path: str) -> Path | None:
    """Map /files/<path> onto a file inside deploy. Reject traversal."""
    path = unquote(urlsplit(raw_path).path)
    prefix = "/files/"
    if not path.startswith(prefix):
        return None
    rel = path[len(prefix) :]
    if not rel or rel.startswith("/") or "\\" in rel or rel.startswith("."):
        return None
    parts = [part for part in rel.split("/") if part]
    if not parts or any(part in ("..", ".") for part in parts):
        return None
    root = deploy.resolve()
    candidate = root.joinpath(*parts).resolve()
    if not candidate.is_relative_to(root) or not candidate.is_file():
        return None
    return candidate


def request_mac(raw_path: str) -> str:
    """Query parameter ``mac``. Empty when absent. Not stored anywhere."""
    values = parse_qs(urlsplit(raw_path).query, keep_blank_values=False).get("mac") or []
    if not values:
        return ""
    mac = values[0].strip()
    if not mac or any(ch in mac for ch in "\r\n"):
        return ""
    return mac[:64]


def _content_type(path: Path) -> str:
    suffix = path.suffix.lower()
    return {
        ".json": "application/json; charset=utf-8",
        ".txt": "text/plain; charset=utf-8",
        ".csv": "text/csv; charset=utf-8",
        ".svg": "image/svg+xml",
        ".html": "text/html; charset=utf-8",
        ".js": "text/javascript; charset=utf-8",
        ".css": "text/css; charset=utf-8",
    }.get(suffix, "application/octet-stream")


class AccessLog:
    """Append-only CSV log of what each device asked the server for.

    Columns: timestamp (UTC), mac, method, path, status.
    `mac` is the query parameter devices send to identify themselves; it is
    empty for browser/curl hits that omit it. The file is opened append-only
    and a header is written only when the file is new.
    """

    FIELDS = ["timestamp", "mac", "method", "path", "status"]

    def __init__(self, path: Path):
        self.path = path
        self.ok = False
        self._lock = threading.Lock()
        self._handle = None
        self._writer = None
        try:
            self._handle = path.open("a", newline="", encoding="utf-8")
            if path.stat().st_size == 0:
                self._writer = csv.writer(self._handle)
                self._writer.writerow(self.FIELDS)
                self._handle.flush()
            else:
                self._writer = csv.writer(self._handle)
            self.ok = True
        except OSError as exc:
            print(f"[store] WARN cannot open access log {path}: {exc}", file=sys.stderr)

    def log(self, method: str, path: str, mac: str, status) -> None:
        if not self.ok:
            return
        try:
            status = int(status)
        except (TypeError, ValueError):
            status = 0
        with self._lock:
            self._writer.writerow(
                [
                    datetime.now(timezone.utc).isoformat(timespec="seconds"),
                    mac,
                    method,
                    path,
                    status,
                ]
            )
            self._handle.flush()


def make_handler(deploy: Path, access_log=None):
    class Handler(BaseHTTPRequestHandler):
        def _cors(self) -> None:
            self.send_header("Access-Control-Allow-Origin", "*")
            self.send_header("Access-Control-Allow-Methods", "GET, OPTIONS")
            self.send_header("Access-Control-Allow-Headers", "Content-Type")

        def _json(self, code: int, obj) -> None:
            body = json.dumps(obj, ensure_ascii=False).encode("utf-8")
            self.send_response(code)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self._cors()
            self.end_headers()
            self.wfile.write(body)

        def do_OPTIONS(self) -> None:
            self.send_response(204)
            self._cors()
            self.end_headers()

        def _catalog(self) -> None:
            raw = urlsplit(self.path)
            q = parse_qs(raw.query, keep_blank_values=False)
            mac = (q.get("mac") or [""])[0].strip()[:64]
            chip = (q.get("chip") or [""])[0].strip()
            try:
                abi_version = int((q.get("abi_version") or ["0"])[0] or 0)
            except ValueError:
                abi_version = 0
            abi_total = (q.get("abi_total_hash") or [""])[0].strip()

            host_abi = load_host_abi(deploy)
            fw_upgrade = build_firmware_upgrade(deploy, chip, abi_version)

            # Step 1: ABI compatibility. The contract is an array of per-version
            # entries; a device identifies itself by abi_version (and optionally
            # abi_total_hash). An unknown version, or a per-version hash mismatch,
            # means no compatible plugins.
            host_symbols = host_abi_symbols_for(host_abi, abi_version)
            if host_abi is not None:
                if abi_version and host_symbols is None:
                    self._json(
                        200,
                        {
                            "status": "no_plugin_for_version",
                            "reason": "abi_version_unknown",
                            "plugins": [],
                            "firmware_upgrade": fw_upgrade,
                        },
                    )
                    return
                if abi_total and host_symbols is not None:
                    entry = next((e for e in host_abi if e.get("version") == abi_version), {}) or {}
                    if entry.get("abi_total_hash") and abi_total != entry.get("abi_total_hash"):
                        self._json(
                            200,
                            {
                                "status": "no_plugin_for_version",
                                "reason": "abi_mismatch",
                                "plugins": [],
                                "firmware_upgrade": fw_upgrade,
                            },
                        )
                        return

            entries = load_all_plugin_entries(deploy)
            latest = latest_per_id(entries)

            do_abi = bool(abi_version) and host_abi is not None
            if do_abi:
                plugins = [e for e in latest.values() if catalog_compatible(e, host_abi, abi_version)]
            else:
                plugins = list(latest.values())

            # Step 2a: chip. The device identifies itself with ?chip=; an entry
            # whose targets name another chip must never be offered. Authorized
            # mac overrides below are appended regardless.
            plugins = [e for e in plugins if plugin_matches_chip(e, chip)]

            # Step 2b: server-authorized overrides (by mac).
            overrides = load_overrides(deploy)
            if mac and isinstance(overrides.get(mac), dict):
                for mid, info in overrides[mac].items():
                    if not isinstance(info, dict):
                        continue
                    allow = info.get("allow_version")
                    if not allow:
                        continue
                    forced = find_plugin_version(entries, mid, allow)
                    if forced and forced not in plugins:
                        plugins.append(forced)

            plugins.sort(key=lambda e: e.get("id", ""))
            self._json(
                200,
                {
                    "status": "ok" if plugins else "no_plugin_for_version",
                    "plugins": plugins,
                    "firmware_upgrade": fw_upgrade,
                },
            )

        def _assets(self, kind: str, name: str) -> None:
            if kind == "device":
                doc = _read_json(deploy / "Assets" / "device_widgets.json")
                table = (doc or {}).get("devices", {})
                entry = table.get(name)
                if not isinstance(entry, dict):
                    # A plugin may register its own device type that the shared
                    # model (devices.csv) knows nothing about. Artwork is keyed by
                    # file name, so honor Assets/images/devices/<type>.svg instead
                    # of 404-ing: dropping the file in is all it takes.
                    art = deploy / "Assets" / "images" / "devices" / f"{name}.svg"
                    if art.is_file():
                        entry = {"icon": f"/files/Assets/images/devices/{name}.svg", "parameters": {}}
            else:
                doc = _read_json(deploy / "Assets" / "parameters.json")
                table = (doc or {}).get("parameters", {})
                entry = table.get(name)
            if not isinstance(entry, dict):
                self.send_error(404)
                return
            self._json(200, entry)

        def do_GET(self) -> None:
            route = urlsplit(self.path).path
            if route == "/api/catalog":
                self._catalog()
                return
            if route == "/api/firmware":
                self._json(200, load_firmware_catalog(deploy))
                return
            if route == "/api/web":
                self._json(200, build_web_index(deploy))
                return
            if route == "/api/assets":
                self._json(200, build_asset_index(deploy))
                return
            m = re.match(r"^/api/assets/(device|parameter)/(.+)$", route)
            if m:
                self._assets(m.group(1), unquote(m.group(2)))
                return
            if route.startswith("/files/"):
                path = resolve_deploy_file(deploy, self.path)
                if not path:
                    self.send_error(404)
                    return
                data = path.read_bytes()
                self.send_response(200)
                self.send_header("Content-Type", _content_type(path))
                self.send_header("Content-Length", str(len(data)))
                self._cors()
                self.end_headers()
                self.wfile.write(data)
                return
            self.send_error(404)

        def log_message(self, fmt: str, *args) -> None:
            try:
                line = fmt % args
            except TypeError:
                line = fmt
            mac = request_mac(self.path)
            if mac:
                line = f"{line} mac={mac}"
            print(f"[store] {self.address_string()} {line}")

        def log_request(self, code="-", size="-") -> None:
            """Hook every response to record the access log row.

            BaseHTTPRequestHandler calls this from ``send_response`` (and thus
            from ``send_error`` too), so a single override covers JSON answers,
            file downloads, OPTIONS preflight, and 404s alike.
            """
            if access_log is not None:
                try:
                    access_log.log(self.command, self.path, request_mac(self.path), code)
                except Exception:  # never break a response over logging
                    pass
            super().log_request(code, size)

    return Handler


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", default=os.environ.get("MINIHUB_STORE_BIND", "0.0.0.0"))
    parser.add_argument("--port", type=int, default=int(os.environ.get("MINIHUB_STORE_PORT", "8080")))
    parser.add_argument(
        "--deploy",
        type=Path,
        default=None,
        help="deploy root (default: MINIHUB_PLUGINS_DEPLOY_DIR or ~/workspace/minihub_store)",
    )
    parser.add_argument(
        "--log-file",
        type=Path,
        default=None,
        help="CSV access log path (default: <deploy>/store_access_log.csv). "
        "Records time, device mac, method, request path, and HTTP status.",
    )
    parser.add_argument(
        "--no-log",
        action="store_true",
        help="disable the access log (it is enabled by default)",
    )
    args = parser.parse_args()
    deploy = resolve_deploy_dir(args.deploy)
    if args.no_log:
        access_log = None
        access_log_str = "disabled"
    else:
        log_path = args.log_file or (deploy / "store_access_log.csv")
        access_log = AccessLog(log_path)
        access_log_str = str(access_log.path) if access_log.ok else f"{log_path} (cannot open)"
    Handler = make_handler(deploy, access_log)
    srv = HTTPServer((args.host, args.port), Handler)
    print(f"MiniHub deploy server listening on http://{args.host}:{args.port}")
    print(f"  deploy:   {deploy}")
    print(f"  access-log: {access_log_str} (CSV: timestamp,mac,method,path,status)")
    print("  catalog:  GET /api/catalog  (Stores/<chip-or-Common>/<id>/catalog.json)")
    print("  firmware: GET /api/firmware (Firmwares/<chip>/<version>/)")
    print("  web:      GET /api/web      (Webs/<version>/)")
    print("  assets:   GET /api/assets   (Assets/)")
    print("            GET /api/assets/device/<id> | /api/assets/parameter/<param>")
    print("  files:    GET /files/<path>")
    srv.serve_forever()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
