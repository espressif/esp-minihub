"""Deploy-root server for plugins, firmware, assets, and web (default :8080).

  MINIHUB_PLUGINS_DEPLOY_DIR  (default ~/workspace/minihub_store)

Routes:
  GET /api/catalog            aggregate Stores/Common/<id>/catalog.json;
                                returns the latest build per plugin id. ``mac`` drives
                                per-device overrides; ``cur_version`` (optional) lets the
                                server flag a newer firmware. ABI (abi_version /
                                abi_total_hash) is optional and only enforced for
                                native plugins. Zero compatible -> {status:
                                "no_plugin_for_version"} plus firmware_upgrade.
  GET /api/firmware           walk Firmwares/<chip>/<version>/ and build the array
  GET /api/web               walk Webs/<version>/ and build the web manifest
  GET /api/assets            walk Assets/ and build the asset manifest
  GET /api/assets/device/<id> device icon + per-parameter meta (404 if unknown);
                             a type absent from model/devices.csv is served from
                             Assets/images/devices/<id>.svg when that file exists
  GET /api/assets/parameter/<param> generic parameter registry entry (404 if unknown)
  GET /files/<path>           file under the deploy root (rejects '..' and escapes)

``mac`` is used only for the server-side overrides authorization.
``cur_version`` is optional; when present the server reports whether a newer
firmware is published (``firmware_upgrade.newer``). ``abi_version`` and
``abi_total_hash`` are optional and only checked when both are supplied
(native compatibility). overrides.json at the deploy root drives
per-device overrides.

Plugin packages for L1 and L2 live under Stores/Common/<id>/<id>.mhub.
Native and hybrid modules are not published, so the server never sees a
``Stores/<chip>/<id>/`` plugin folder. Firmware folders hold
<name>.bin and release_notes.txt only -- no json. Asset and web indexes are
generated by gen_deploy_index.py.
"""

