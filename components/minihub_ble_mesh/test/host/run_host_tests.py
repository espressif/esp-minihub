"""Build and run the BLE Mesh host tests.

    python3 components/minihub_ble_mesh/test/host/run_host_tests.py

Two binaries: the capability map + sensor decode, and the adapter. The real
component sources are compiled against small esp_err / esp_log / FreeRTOS stubs
and the same cJSON the firmware links, so neither the parser nor the table is
duplicated here. The adapter binary also links the real device-widget catalog,
generated from model/*.csv exactly as the firmware build does.

cJSON comes from the managed component, which any `tools/build_firmware.py` run
fetches; set MINIHUB_CJSON_DIR to point elsewhere.

Set MINIHUB_HOST_TEST_LOG=1 to see the components' own log output.
"""

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HOST_DIR = Path(__file__).resolve().parent
COMP_DIR = HOST_DIR.parent.parent
REPO_ROOT = COMP_DIR.parent.parent
MAP_JSON = COMP_DIR / "config" / "ble_mesh_map.json"

STUBS = HOST_DIR / "stubs"
TESTS = HOST_DIR / "test_ble_mesh_host.c"
ADAPTER_TESTS = HOST_DIR / "test_ble_mesh_adapter.c"
ADAPTER_DIR = REPO_ROOT / "components" / "minihub_protocol_adapters" / "adapter_ble_mesh"
WIDGET_DIR = REPO_ROOT / "components" / "minihub_device_widget"


def find_cjson() -> Path:
    override = os.environ.get("MINIHUB_CJSON_DIR")
    if override:
        path = Path(override).expanduser().resolve()
        if (path / "cJSON.c").is_file():
            return path
        sys.exit(f"MINIHUB_CJSON_DIR={path} has no cJSON.c")
    for app in sorted((REPO_ROOT / "application").glob("*")):
        path = app / "managed_components" / "espressif__cjson" / "cJSON"
        if (path / "cJSON.c").is_file():
            return path
    sys.exit(
        "cJSON not found. Build the firmware once so the managed component is "
        "downloaded (tools/build_firmware.py -app minihub build), or set "
        "MINIHUB_CJSON_DIR to a directory holding cJSON.c / cJSON.h."
    )


def write_embed(dest: Path) -> None:
    """Reproduce CMake's EMBED_TXTFILES symbols for the default map."""
    data = MAP_JSON.read_bytes()
    # asm() labels are verbatim assembler names on both Mach-O and ELF.
    start = "_binary_ble_mesh_map_json_start"
    end = "_binary_ble_mesh_map_json_end"
    lines = [
        "/* Generated by run_host_tests.py from config/ble_mesh_map.json. */",
        "#include <stdint.h>",
        f'const uint8_t ble_mesh_map_json_start[] __asm__("{start}") = {{',
    ]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i : i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append(f'__asm__(".globl {end}\\n.set {end}, {start} + {len(data)}");')
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")


def compile_one(cc: Path, src: Path, obj: Path, includes: list[str], flags: list[str]) -> None:
    cmd = [str(cc), "-std=gnu11", *flags, *[f"-I{p}" for p in includes], "-c", str(src), "-o", str(obj)]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.stdout:
        sys.stdout.write(proc.stdout)
    if proc.stderr:
        sys.stderr.write(proc.stderr)
    if proc.returncode != 0:
        raise SystemExit(f"compile failed ({proc.returncode}): {src}")


def build_and_run(cc: Path, build: Path, name: str, sources: list[tuple[Path, list[str]]],
                  includes: list[str]) -> int:
    obj_dir = build / name
    obj_dir.mkdir(parents=True, exist_ok=True)
    objs = []
    for src, flags in sources:
        obj = obj_dir / (src.stem + ".o")
        compile_one(cc, src, obj, includes, flags)
        objs.append(obj)
    binary = obj_dir / name
    subprocess.run([str(cc), *[str(o) for o in objs], "-o", str(binary)], check=True)
    return subprocess.run([str(binary)]).returncode


def write_sdkconfig(dest: Path) -> None:
    """The adapter's control paths are behind CONFIG_MINIHUB_BLE_MESH_SDK."""
    dest.write_text(
        "/* Generated by run_host_tests.py: the real mesh control paths, not simulation. */\n"
        "#define CONFIG_MINIHUB_BLE_MESH_SDK 1\n",
        encoding="utf-8",
    )


def generate_widget_catalog(build: Path) -> Path:
    """Run the firmware's own generator so the tests assert on the real catalog."""
    out = build / "widget"
    out.mkdir(parents=True, exist_ok=True)
    # MINIHUB_DW_MODEL_DIR has to be a different directory from the flat file's
    # parent, or the flattener would read back its own output as its input.
    (out / "model").mkdir(exist_ok=True)
    proc = subprocess.run(
        [sys.executable, str(WIDGET_DIR / "tools" / "gen_device_widget.py"), "--out-dir", str(out)],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        raise SystemExit(f"gen_device_widget.py failed ({proc.returncode})")
    gen = out / "minihub_device_widget_gen.c"
    if not gen.is_file():
        raise SystemExit(f"generator produced no {gen.name}")
    return out


def main() -> int:
    cjson = find_cjson()
    cc = Path(shutil.which(os.environ.get("CC", "cc")) or "cc")
    build = Path(tempfile.mkdtemp(prefix="bm_host_test_"))
    strict = ["-Wall", "-Wextra", "-Werror"]
    # The host libc's fortified string helpers and stack protector reference
    # symbols the firmware's own libc provides; neither is under test here.
    host_flags = ["-D_FORTIFY_SOURCE=0", "-fno-stack-protector"]

    base_includes = [
        str(STUBS),
        str(COMP_DIR),
        str(COMP_DIR / "include"),
        str(REPO_ROOT / "components" / "minihub_core" / "include"),
        str(cjson),
    ]
    embed = build / "embed_map_json.c"
    write_embed(embed)
    # The report-block tests write this file themselves; the firmware path stays /data.
    overlay = build / "bm_map_overlay.json"
    map_flags = [*strict, f'-DMINIHUB_BM_MAP_DATA_PATH="{overlay}"']
    common = [
        (STUBS / "esp_stubs.c", strict),
        (embed, strict),
        (COMP_DIR / "ble_mesh_map.c", map_flags),
        (COMP_DIR / "ble_mesh_sensor.c", strict),
        (cjson / "cJSON.c", ["-w"]),  # third party
    ]

    try:
        rc = build_and_run(cc, build, "test_ble_mesh_host",
                           [*common, (TESTS, map_flags)], base_includes)

        sdkconfig = build / "sdkconfig.h"
        write_sdkconfig(sdkconfig)
        widget_out = generate_widget_catalog(build)
        # Keep every catalog path inside the build tree: the tests must not read
        # or seed anything under /data on the machine running them.
        widget_flags = [
            *strict,
            *host_flags,
            f'-DMINIHUB_DW_CSV_PATH="{widget_out / "devices.csv"}"',
            f'-DMINIHUB_DW_MODEL_DIR="{widget_out / "model"}"',
            f'-DMINIHUB_DW_IMAGES_DIR="{widget_out / "images"}"',
            f'-DMINIHUB_DW_TEST_MODEL_SRC="{WIDGET_DIR / "model"}"',
        ]
        adapter_includes = [
            *base_includes,
            str(build),
            str(ADAPTER_DIR),
            str(ADAPTER_DIR / "include"),
            str(WIDGET_DIR / "include"),
            str(REPO_ROOT / "components" / "minihub_adapter" / "include"),
            str(REPO_ROOT / "components" / "minihub_module" / "include"),
            str(REPO_ROOT / "components" / "minihub_product_params" / "include"),
        ]
        adapter_sources = [
            (STUBS / "esp_stubs.c", [*strict, *host_flags]),
            (STUBS / "hub_stubs.c", [*strict, *host_flags]),
            (embed, [*strict, *host_flags]),
            (COMP_DIR / "ble_mesh_map.c", [*strict, *host_flags]),
            (COMP_DIR / "ble_mesh_sensor.c", [*strict, *host_flags]),
            (WIDGET_DIR / "src" / "minihub_device_widget.c", widget_flags),
            (WIDGET_DIR / "src" / "minihub_device_widget_model.c", widget_flags),
            (widget_out / "minihub_device_widget_gen.c", [*strict, *host_flags]),
            (ADAPTER_TESTS, widget_flags),
            (cjson / "cJSON.c", ["-w", *host_flags]),
        ]
        rc |= build_and_run(cc, build, "test_ble_mesh_adapter", adapter_sources, adapter_includes)
    except (SystemExit, subprocess.CalledProcessError):
        print(f"build tree kept for inspection: {build}", file=sys.stderr)
        raise
    shutil.rmtree(build, ignore_errors=True)
    return rc


if __name__ == "__main__":
    sys.exit(main())
